import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const load = (day) => JSON.parse(fs.readFileSync(path.join(root, "data/canonical-fixtures", day, "syr.1.json"), "utf8"));
const id = "KdKrgosB";
test("2026-10-30 Foutoua correction retains exact identity and no fabricated result", () => {
  const old = load("2026-10-30");
  const next = load("2026-11-01");
  assert.equal(old.count, old.fixtures.length);
  assert.equal(next.count, next.fixtures.length);
  const rows = old.fixtures.filter(f => f.sourceId === id);
  const moved = next.fixtures.filter(f => f.sourceId === id);
  assert.equal(rows.length, 1);
  assert.equal(moved.length, 1);
  const [original] = rows, [rescheduled] = moved;
  assert.equal(original.canonicalId, "cid_syr1_foutoua_aljaish_20261030");
  assert.equal(rescheduled.canonicalId, "cid_syr1_foutoua_aljaish_20261101");
  assert.equal(original.dayKey, "2026-10-30");
  assert.equal(rescheduled.dayKey, "2026-11-01");
  assert.equal(original.kickoffUtc, "2026-10-30T12:00:00.000Z");
  assert.equal(rescheduled.kickoffUtc, "2026-11-01T12:00:00.000Z");
  assert.equal(original.homeTeam, rescheduled.homeTeam);
  assert.equal(original.awayTeam, rescheduled.awayTeam);
  assert.equal(original.leagueSlug, rescheduled.leagueSlug);
  assert.equal(original.providerIds.flashscore, id);
  assert.equal(rescheduled.providerIds.flashscore, id);
  assert.equal(original.status, "STATUS_POSTPONED");
  assert.equal(original.rawStatus, "STATUS_POSTPONED");
  assert.equal(original.statusType, "STATUS_POSTPONED");
  assert.equal(original.scoreHome, null);
  assert.equal(original.scoreAway, null);
  assert.equal(original.statusCorrection?.originalMatch?.providerMatchId, id);
  assert.equal(original.statusCorrection?.rescheduledMatch?.providerMatchId, id);
  assert.equal(original.statusCorrection?.publicationAuthorized, false);
  assert.equal(original.statusCorrection?.providerNativeStatusCodeVerified, false);
  assert.equal(rescheduled.status, "STATUS_SCHEDULED");
  assert.equal(rescheduled.scoreHome, null);
  assert.equal(rescheduled.scoreAway, null);
  assert.equal(old.fixtures.filter(f => f.status === "FT").length, 4);
  assert.equal(old.fixtures.filter(f => f.status === "STATUS_POSTPONED").length, 1);
});
